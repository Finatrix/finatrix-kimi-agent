/**
 * The full expense report.
 *
 * Page 1 leads with the summary a reader needs first (income, expenses,
 * savings, budget utilisation, remaining, net cash flow), then budget vs
 * expense as a chart and as a table, then the spending highlights and the
 * category mix. Every transaction follows in a ruled table — all of them,
 * however many there are; the table paginates, the data is never truncated.
 */
export async function exportExpensePdf(e: ExpenseExport) {
  const [{ jsPDF }, autoTableMod, logo] = await Promise.all([
    import('jspdf'), import('jspdf-autotable'), loadLogo(),
  ]);
  const autoTable = autoTableMod.default;
  const doc = new jsPDF({ unit: 'pt', format: 'a4' }) as Doc;
  const m = (n: number) => money(n, e.currency);

  let y = drawHeader(doc, {
    title: 'Expense Report', period: e.monthLabel, currency: e.currency, logo,
  });

  /* ── Summary cards ── */
  const used = e.budgetUsedPct ?? (e.budget > 0 ? (e.totalSpent / e.budget) * 100 : 0);
  const remaining = budgetRemainingOf(e);
  const cards: StatCard[] = [
    {
      label: 'Total income',
      value: e.income != null && e.income > 0 ? m(e.income) : '—',
      note: e.income != null && e.income > 0 ? 'From Budget Builder' : 'Set income in Budget Builder',
      accent: TONE_RGB.complete,
    },
    { label: 'Total expenses', value: m(e.totalSpent), note: `${e.txCount} transactions`, accent: TONE_RGB.warn },
    {
      label: 'Savings',
      value: e.monthlySavings != null ? m(e.monthlySavings) : '—',
      note: e.income != null && e.income > 0 && e.monthlySavings != null
        ? `${pct((e.monthlySavings / e.income) * 100)} of income`
        : 'Savings-category spend',
      accent: TONE_RGB.safe,
    },
    {
      label: 'Budget utilisation',
      value: e.budget > 0 ? pct(used) : '—',
      note: e.budget > 0 ? `of ${m(e.budget)} budget` : 'No budget set',
      accent: TONE_RGB[budgetTone(e.budget, e.totalSpent)],
    },
    {
      label: e.budget > 0 && remaining < 0 ? 'Budget overrun' : 'Budget remaining',
      value: e.budget > 0 ? m(Math.abs(remaining)) : '—',
      note: e.daysRemaining != null && e.daysRemaining > 0 ? `${e.daysRemaining} days left in month` : 'Month complete',
      accent: remaining < 0 ? TONE_RGB.over : TONE_RGB.safe,
    },
    {
      label: 'Net cash flow',
      value: e.netCashFlow != null ? m(e.netCashFlow) : '—',
      note: e.netCashFlow != null ? (e.netCashFlow >= 0 ? 'Income exceeds spending' : 'Spending exceeds income') : 'Needs an income figure',
      accent: (e.netCashFlow ?? 0) >= 0 ? TONE_RGB.safe : TONE_RGB.over,
    },
  ];
  y = drawStatCards(doc, y, cards);

  /* ── Budget vs expense ── */
  const budgeted = (e.categoryBudgets ?? []).filter((c) => c.budget > 0 || c.spent > 0);
  if (budgeted.length > 0) {
    const chartRows = [...budgeted]
      .sort((a, b) => Math.max(b.budget, b.spent) - Math.max(a.budget, a.spent))
      .slice(0, 10);
    y = sectionTitle(doc, y, 'Budget vs expense', `Top ${chartRows.length} categories by size`);
    y = drawGroupedBars(doc, y, chartRows.map((c) => ({ label: c.label, budget: c.budget, spent: c.spent })), e.currency);

    y = sectionTitle(doc, y, 'Category detail');
    autoTable(doc, {
      ...TABLE_STYLES,
      startY: y,
      head: [['Category', 'Budget', 'Expense', 'Remaining', 'Status']],
      body: [...budgeted]
        .sort((a, b) => b.spent - a.spent)
        .map((c) => [
          c.label, m(c.budget), m(c.spent), m(c.budget - c.spent),
          TONE_EXPORT_LABEL[budgetTone(c.budget, c.spent)],
        ]),
      columnStyles: {
        1: { halign: 'right' }, 2: { halign: 'right' }, 3: { halign: 'right' },
        4: { halign: 'center', fontStyle: 'bold' },
      },
      // Colour the status column to match the app's own tone scale, so the
      // printed table carries the same signal as the screen.
      didParseCell: (raw: unknown) => {
        const data = raw as {
          section: string; column: { index: number };
          cell: { text: string[]; styles: { textColor: unknown } };
        };
        if (data.section !== 'body' || data.column.index !== 4) return;
        const label = data.cell.text?.[0];
        const tone = (Object.keys(TONE_EXPORT_LABEL) as Array<keyof typeof TONE_EXPORT_LABEL>)
          .find((k) => TONE_EXPORT_LABEL[k] === label);
        if (tone) data.cell.styles.textColor = TONE_RGB[tone];
      },
    });
    y = lastY(doc, y) + 22;
  }

  /* ── Spending highlights ── */
  const big = largestExpense(e);
  const topCat = largestCategory(e);
  y = sectionTitle(doc, y, 'Top spending');
  y = drawStatCards(doc, y, [
    {
      label: 'Largest expense',
      value: big ? m(big.amount) : '—',
      note: big ? clip(`${txLabel(big)} · ${big.date}`, 34) : 'No transactions',
      accent: TONE_RGB.over,
    },
    { label: 'Average daily spending', value: m(e.dailyAvg), note: e.daysInMonth ? `Across ${e.daysInMonth} days` : 'This period', accent: GOLD },
    {
      label: 'Largest category',
      value: topCat ? m(topCat.amount) : '—',
      note: topCat ? clip(`${topCat.label} · ${pct(topCat.pct)} of spend`, 34) : 'No spending yet',
      accent: TONE_RGB.warn,
    },
  ]);

  /* ── Category breakdown ── */
  if (e.breakdown.length > 0) {
    y = sectionTitle(doc, y, 'Category breakdown', 'Share of everything logged this period');
    y = drawDonut(doc, y, e.breakdown.map((b) => ({ label: b.label, amount: b.amount })), e.currency);
  }

  /* ── All transactions ── */
  // Continue on this page when there is room for the heading and a few rows;
  // an unconditional page break here left half-empty pages in the middle of the
  // report. autoTable paginates the rest on its own.
  const ty = sectionTitle(
    doc, ensureSpace(doc, y, 150),
    'All transactions', `${e.transactions.length} of ${e.txCount} for ${e.monthLabel}`,
  );
  autoTable(doc, {
    ...TABLE_STYLES,
    startY: ty,
    head: [['Date', 'Category', 'Merchant / note', 'Payment', 'Amount']],
    body: e.transactions.map((t) => [
      t.date,
      t.category,
      [t.merchant, t.note].filter(Boolean).join(' — '),
      t.paymentMethod ?? '',
      m(t.amount),
    ]),
    columnStyles: {
      0: { cellWidth: 62 }, 3: { cellWidth: 66 },
      4: { halign: 'right', cellWidth: 78, fontStyle: 'bold', textColor: INK },
    },
    foot: [['', '', '', 'Total', m(e.totalSpent)]],
    footStyles: { fillColor: [240, 238, 232], textColor: INK, fontStyle: 'bold', fontSize: 8.5, halign: 'right' },
  });

  stampFooters(doc, FOOT_NOTE);
  doc.save(`finatrix-expenses-${slug(e.monthLabel)}.pdf`);
}
