/**
 * Branded exporters for Budget Builder and Expense Tracker — CSV, Excel (.xlsx)
 * and PDF. Heavy libraries (xlsx, jspdf) are dynamically imported so they never
 * enter the main bundle; they load only when the user actually exports.
 *
 * Exports are built from the caller's complete data set, never from what the
 * screen happens to be rendering: pagination, virtualisation and "recent N"
 * previews are display concerns and must never reach a report.
 *
 * Every export carries FinatriX branding, the generation date (local time), the
 * active currency, totals and a summary; PDFs add the full report layout from
 * pdfReport.ts (masthead, stat cards, charts, ruled tables, page numbers).
 */
