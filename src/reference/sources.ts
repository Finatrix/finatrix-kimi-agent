/** Indexed once at module load; `sourceById` is called on every render path. */
const BY_ID: ReadonlyMap<string, ReferenceSource> = new Map(SOURCES.map((s) => [s.id, s]));

/** The record, or undefined. Never throws — a missing citation must not break a page. */
export function sourceById(id: string): ReferenceSource | undefined {
  return BY_ID.get(id);
}

/** Resolve a list of ids, silently dropping any that do not exist. */
export function sourcesByIds(ids: readonly string[]): readonly ReferenceSource[] {
  return ids.map(sourceById).filter((s): s is ReferenceSource => s !== undefined);
}
