/**
 * The master source registry — 105 dated, checkable references.
 *
 * WHY IDS AND NOT URLS
 * --------------------
 * Before this file, provenance lived as prose inside each market pack:
 * "ONS Household Total Wealth statistics" in one place, "Published best-buy
 * rates" in another, "Income Tax Act provisions current for AY 2026-27" in a
 * third. Three problems followed. A reader could not click any of them. The
 * same authority was described differently depending on which tool you were
 * looking at. And nothing carried a date, so a source could quietly stop
 * describing current law without anything in the product noticing.
 *
 * An id fixes all three. `UK-FSCS-001` resolves to one record with a URL, an
 * effective date, a verification date and a review date, and every tool that
 * cites the FSCS cites the same record. When the URL changes the record's URL
 * changes and the id does not, so saved results keep pointing at the right
 * thing.
 *
 * ON `lastVerified`
 * -----------------
 * Every date here is 2026-09-12 because that is when the independent research
 * pack these records came from was compiled. FinatriX did not re-open 105
 * government pages; it imported a dated extraction, and the honest thing is to
 * carry that date rather than stamp today's. `verificationScope` says what was
 * actually checked — the extracted claim, never the whole page.
 *
 * ON TIERS
 * --------
 * A tier describes what KIND of body published something, not how much to trust
 * it. Legislation is tier 1 and has nothing to say about consumer price indices;
 * a national statistics office is tier 4 and is the only acceptable authority on
 * its own household survey. `preferSourceFor` in `resolve.ts` ranks by topic
 * competence first and tier second, for exactly that reason.
 *
 * GENERATED-SHAPED, MAINTAINED BY HAND. Records are ordered by market then
 * topic. Adding one means adding a record here and nowhere else.
 */

