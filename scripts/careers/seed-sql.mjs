#!/usr/bin/env node
/**
 * Turns scripts/careers/employers.seed.json (live-verified by verify-employers.mjs) into the career_sources
 * seed migration. Re-run after editing the JSON:
 *
 *   node scripts/careers/seed-sql.mjs
 *
 * A test (supabase/functions/careers-scan/seed.test.ts) fails when the migration and the JSON drift apart.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const SEED_JSON = join(ROOT, 'scripts/careers/employers.seed.json');
export const SEED_MIGRATION = join(ROOT, 'supabase/migrations/20261024000200_careers_engine_seed.sql');

/** Provider names the verifier uses → the engine's provider ids. */
export const PROVIDER_IDS = { oracle: 'oraclecloud' };

const MARKETS = new Set(['us', 'gb', 'in', 'au', 'nz']);

const quote = (value) => `'${String(value).replace(/'/g, "''")}'`;

/** One career_sources row per employer; re-running the migration updates rows in place and never re-enables one. */
export function seedSql(entries) {
  const rows = entries.map((e) => {
    const markets = [...new Set(e.markets)];
    if (!markets.length || markets.some((m) => !MARKETS.has(m))) throw new Error(`${e.name}: unsupported markets ${markets}`);
    if (!/^https:\/\//.test(e.careers_url)) throw new Error(`${e.name}: careers_url must be https`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(e.verified_at)) throw new Error(`${e.name}: verified_at must be YYYY-MM-DD`);
    const provider = PROVIDER_IDS[e.provider] ?? e.provider;
    const options = e.options ? JSON.stringify(e.options) : '{}';
    return `  (${quote(e.name)}, ${quote(provider)}, ${quote(e.careers_url)}, ${quote(`{${markets.join(',')}}`)}::text[], ${quote(options)}::jsonb, ${quote(e.verified_at)}::date)`;
  });
  return `-- Starter employer registry for the careers engine: ${entries.length} employers, each live-verified by
-- scripts/careers/verify-employers.mjs. Generated by scripts/careers/seed-sql.mjs from
-- scripts/careers/employers.seed.json; edit the JSON and regenerate rather than editing this file.
--
-- Re-running updates names, providers, markets and options in place. It never re-enables an employer that was
-- switched off, and never touches scan state.

insert into public.career_sources (name, provider, careers_url, markets, options, verified_on) values
${rows.join(',\n')}
on conflict (careers_url) do update set
  name        = excluded.name,
  provider    = excluded.provider,
  markets     = excluded.markets,
  options     = excluded.options,
  verified_on = excluded.verified_on;
`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const entries = JSON.parse(readFileSync(SEED_JSON, 'utf8'));
  writeFileSync(SEED_MIGRATION, seedSql(entries));
  console.log(`wrote ${entries.length} employers to ${SEED_MIGRATION}`);
}
